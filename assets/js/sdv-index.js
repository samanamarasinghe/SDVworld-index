  /* A plain toggle with a floor: off lights, on unlights, and a group is never left
     empty because an empty group would show nothing at all. What the floor does differs
     by group, which is deliberate -- switching off the last lit half of the pair hands
     the selection to the other half, so one click flips it, while switching off the last
     lit region reopens every region, so one click clears the filter. */
  function toggleAff(grp, v) {
    var sel = state.sel[grp.facet], any = false;
    if (!sel[v]) { sel[v] = true; applyFilters(); return; }
    sel[v] = false;
    grp.values.forEach(function (x) { if (sel[x]) any = true; });
    if (!any) {
      grp.values.forEach(function (x) {
        if (grp.onEmpty === 'all' || x !== v) sel[x] = true;
      });
    }
    applyFilters();
  }

  /* The importance slider has 7 discrete stops and nothing in its native rendering says
     so. One mark per step, read off the input's own min/max/step so the marks and the
     control cannot disagree, and drawn once since the scale never changes. */
  function buildStopMarks(input, mount) {
    if (!input || !mount) return;
    var min = parseFloat(input.min), max = parseFloat(input.max), step = parseFloat(input.step);
    if (!(step > 0) || !(max > min)) return;
    var n = Math.round((max - min) / step);
    mount.innerHTML = '';
    for (var i = 0; i <= n; i++) {
      mount.appendChild(el('span', 'slider-tick' + (i === 0 || i === n ? ' tick-end' : '')));
    }
  }


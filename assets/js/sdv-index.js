  /* A pooled record that has since been curated into a shard must not appear twice:
     the tail files still hold every harvested row, curated or not. Match on URL,
     normalized, since ids differ between the pool and the curated entry. */
  var CURATED_URLS = null;
  function urlKey(u) {
    return String(u || '').toLowerCase().replace(/^https?:\/\//, '').replace(/\/+$/, '');
  }
  function curatedUrls() {
    if (!CURATED_URLS) {
      CURATED_URLS = {};
      DATA.forEach(function (r) { if (r.url) CURATED_URLS[urlKey(r.url)] = 1; });
    }
    return CURATED_URLS;
  }
  /* A work can be reached by three different pointers -- its landing page, its
     DOI, its OpenAlex id -- and a curator may have filed it under any one of
     them. Matching only the pointer we happen to display leaves the entry in
     both the index and the pool, so check every alias the row carries. */
  function notCurated(r) {
    var map = curatedUrls(), keys = r.alt_urls || [r.url];
    for (var i = 0; i < keys.length; i++) {
      if (keys[i] && map[urlKey(keys[i])]) return false;
    }
    return true;
  }


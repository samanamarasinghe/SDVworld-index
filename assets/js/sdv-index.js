/* SDV Ecosystem Index — filter/render controller.
   Data source: data/sdv-index.json (generated by build.py from data/shards/).
   Optional citation tail: data/tail/openalex-citations.json (lazy-loaded). */
(function () {
  'use strict';

  var INDEX_PATH  = 'data/sdv-index.json';
  var TAIL_PATH   = 'data/tail/openalex-citations.json';
  var GITHUB_PATH = 'data/tail/github-repos.json';

  var TYPE2KIND = {
    article: 'paper', 'conference-paper': 'paper', review: 'paper', 'book-chapter': 'paper',
    preprint: 'preprint', dissertation: 'thesis', book: 'paper', 'data-paper': 'dataset_benchmark',
    dataset: 'dataset_benchmark', 'software-paper': 'paper'
  };
  var HITS2COMPONENT = {
    st: 'sdv', md: 'sdv', mt: 'sdv', sq: 'sdv', ev: 'sdv', gc: 'sdv', par: 'sdv', hma: 'sdv', req: 'sdv',
    ct: 'ctgan', sm: 'sdmetrics', rdt: 'rdt', gym: 'sdgym'
  };

  /* ---------- Labels ---------- */
  var KIND_LABELS = {
    paper: 'Paper', preprint: 'Preprint', thesis: 'Thesis', blog_post: 'Blog post',
    announcement: 'Announcement', case_study: 'Case study', news_article: 'News article',
    documentation: 'Documentation', code_repo: 'Code repo', tutorial: 'Tutorial',
    video: 'Video', dataset_benchmark: 'Dataset / benchmark', forum: 'Forum', patent: 'Patent'
  };
  var COMPONENT_LABELS = {
    sdv: 'SDV', ctgan: 'CTGAN', rdt: 'RDT', sdmetrics: 'SDMetrics', sdgym: 'SDGym',
    copulas: 'Copulas', deepecho: 'DeepEcho', tgan: 'TGAN', enterprise: 'Enterprise'
  };
  var USECASE_LABELS = {
    privacy_protection: 'Privacy protection', anonymization: 'Anonymization',
    data_sharing: 'Data sharing', software_testing: 'Software testing',
    data_augmentation: 'Data augmentation', class_imbalance: 'Class imbalance',
    ml_training: 'ML training', benchmarking_evaluation: 'Benchmarking & evaluation',
    scenario_simulation: 'Scenario simulation', method_research: 'Method research',
    compliance: 'Compliance', education: 'Education'
  };
  var INDUSTRY_LABELS = {
    healthcare_bio: 'Healthcare & bio', finance_insurance: 'Finance & insurance',
    government_public: 'Government & public', academia: 'Academia',
    energy_utilities: 'Energy & utilities', telecom: 'Telecom',
    retail_ecommerce: 'Retail & e-commerce', transportation: 'Transportation',
    manufacturing: 'Manufacturing', software: 'Software', cross_industry: 'Cross-industry'
  };
  var INTEGRATION_LABELS = {
    api_user: 'API user', vendored_source: 'Vendored source',
    derivative_work: 'Derivative work', baseline_only: 'Baseline only',
    citation_only: 'Citation only', source_work: 'Source work',
    name_collision: 'Name collision', unclear: 'Unclear'
  };
  var CONF_RANK = { high: 3, medium: 2, low: 1 };
  var KIND_ORDER = ['paper', 'preprint', 'thesis', 'code_repo', 'documentation',
    'blog_post', 'announcement', 'case_study', 'tutorial', 'video',
    'dataset_benchmark', 'news_article', 'forum', 'patent'];
  var CITABLE = { paper: 1, preprint: 1, thesis: 1 };

  function prettify(v) {
    return String(v || '').replace(/_/g, ' ').replace(/^./, function (c) { return c.toUpperCase(); });
  }
  function labelFor(facet, v) {
    if (facet === 'kind') return KIND_LABELS[v] || prettify(v);
    if (facet === 'sdv_component') return COMPONENT_LABELS[v] || v;
    if (facet === 'use_case') return USECASE_LABELS[v] || prettify(v);
    if (facet === 'industry') return INDUSTRY_LABELS[v] || prettify(v);
    if (facet === 'confidence') return prettify(v);
    return v;
  }

  /* ---------- Facet model ---------- */
  var FACET_KEYS = ['kind', 'sdv_component', 'use_case', 'industry', 'confidence', 'authors', 'year'];
  var MOUNTS = {
    kind: 'facet-kind', sdv_component: 'facet-component', use_case: 'facet-usecase',
    industry: 'facet-industry', confidence: 'facet-confidence', authors: 'facet-authors',
    year: 'facet-years'
  };

  function valuesOf(rec, facet) {
    switch (facet) {
      case 'kind': return rec.kind ? [rec.kind] : [];
      case 'sdv_component': return rec.sdv_component || [];
      case 'use_case': return rec.use_case || [];
      case 'industry': return rec.industry || [];
      case 'confidence': return rec.confidence ? [rec.confidence] : [];
      case 'authors': return rec.authors || [];
      case 'year': return rec.year ? [String(rec.year)] : [];
    }
    return [];
  }

  /* ---------- State ---------- */
  var state = {
    titleQuery: '', authorQuery: '',
    sel: { kind: {}, sdv_component: {}, use_case: {}, industry: {}, confidence: {}, authors: {}, year: {} },
    group: 'kind', sortWithin: 'year',
    summaryExpanded: false, showTail: false, showGithub: false, minStars: 2
  };

  var DATA = [];
  var CITE = null;         // citation tail, normalized (lazy)
  var GH = null;           // github repo tail, normalized (lazy)
  var UNIVERSE = {};       // facet -> all values present

  function activeData() {
    var out = DATA;
    if (state.showTail && CITE) out = out.concat(CITE);
    if (state.showGithub && GH) out = out.concat(GH.filter(function (r) { return (r.stars || 0) >= state.minStars; }));
    return out;
  }

  var els = {};
  function $(id) { return document.getElementById(id); }

  /* ---------- Small DOM helpers ---------- */
  function el(tag, cls, txt) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (txt != null) e.appendChild(document.createTextNode(txt));
    return e;
  }
  function selected(map) {
    var out = [], k;
    for (k in map) if (map[k]) out.push(k);
    return out;
  }

  /* ---------- Filtering ---------- */
  function matchesSearch(rec, q) {
    if (!q) return true;
    return ((rec.title || '') + ' ' + (rec.summary || '')).toLowerCase().indexOf(q) >= 0;
  }
  function passesFacets(rec, exclude) {
    for (var i = 0; i < FACET_KEYS.length; i++) {
      var fk = FACET_KEYS[i];
      if (fk === exclude) continue;
      var sel = selected(state.sel[fk]);
      if (!sel.length) continue;
      var vals = valuesOf(rec, fk), hit = false;
      for (var j = 0; j < sel.length; j++) if (vals.indexOf(sel[j]) >= 0) { hit = true; break; }
      if (!hit) return false;
    }
    return true;
  }
  function filteredData(exclude) {
    var q = state.titleQuery.replace(/\s+/g, ' ').trim().toLowerCase();
    return activeData().filter(function (rec) { return matchesSearch(rec, q) && passesFacets(rec, exclude); });
  }

  /* ---------- Facet rendering ---------- */
  function countValues(records, facet) {
    var c = {};
    for (var i = 0; i < records.length; i++) {
      var vals = valuesOf(records[i], facet);
      for (var j = 0; j < vals.length; j++) c[vals[j]] = (c[vals[j]] || 0) + 1;
    }
    return c;
  }

  function buildCheckboxFacet(facet) {
    var mount = els[facet];
    var counts = countValues(filteredData(facet), facet);
    var values = UNIVERSE[facet].slice();

    if (facet === 'confidence') {
      values.sort(function (a, b) { return (CONF_RANK[b] || 0) - (CONF_RANK[a] || 0); });
    } else if (facet === 'authors') {
      var q = state.authorQuery.trim().toLowerCase();
      if (q) values = values.filter(function (v) { return v.toLowerCase().indexOf(q) >= 0; });
      values.sort(function (a, b) {
        var d = (counts[b] || 0) - (counts[a] || 0);
        return d !== 0 ? d : a.localeCompare(b);
      });
      if (!q && values.length > 200) values = values.slice(0, 200);
    } else {
      values.sort(function (a, b) {
        var d = (counts[b] || 0) - (counts[a] || 0);
        return d !== 0 ? d : labelFor(facet, a).localeCompare(labelFor(facet, b));
      });
    }

    var wrap = el('div', 'facet-scroll');
    var list = el('div', 'facet-items');
    for (var i = 0; i < values.length; i++) {
      var v = values[i], n = counts[v] || 0, on = !!state.sel[facet][v];
      var label = el('label', 'facet-item' + (n === 0 && !on ? ' disabled' : ''));
      var cb = document.createElement('input');
      cb.type = 'checkbox'; cb.value = v; cb.checked = on;
      cb.onchange = (function (val) {
        return function () { state.sel[facet][val] = this.checked; applyFilters(); };
      })(v);
      label.appendChild(cb);
      if (facet === 'confidence') label.appendChild(el('span', 'conf-dot conf-' + v));
      var txt = el('span', 'facet-text', labelFor(facet, v) + ' (' + n + ')');
      txt.title = labelFor(facet, v);
      label.appendChild(txt);
      list.appendChild(label);
    }
    wrap.appendChild(list);
    mount.innerHTML = '';
    mount.appendChild(wrap);
  }

  function buildYearGrid() {
    var mount = els.year;
    var counts = countValues(filteredData('year'), 'year');
    var years = UNIVERSE.year.slice().sort(function (a, b) { return parseInt(b, 10) - parseInt(a, 10); });
    mount.innerHTML = '';
    for (var i = 0; i < years.length; i++) {
      var y = years[i], n = counts[y] || 0, on = !!state.sel.year[y];
      var btn = el('button', 'year-btn' + (on ? ' active' : ''));
      btn.type = 'button';
      btn.appendChild(document.createTextNode(y + ' '));
      btn.appendChild(el('span', 'year-badge', String(n)));
      btn.onclick = (function (yy) {
        return function () { state.sel.year[yy] = !state.sel.year[yy]; applyFilters(); };
      })(y);
      mount.appendChild(btn);
    }
  }

  function rebuildFacets() {
    buildCheckboxFacet('kind');
    buildCheckboxFacet('sdv_component');
    buildCheckboxFacet('use_case');
    buildCheckboxFacet('industry');
    buildCheckboxFacet('confidence');
    buildCheckboxFacet('authors');
    buildYearGrid();
  }

  /* ---------- Result cards ---------- */
  function actionLabel(rec) {
    if (rec.kind === 'code_repo') return /github\.com/i.test(rec.url || '') ? 'GitHub' : 'Repository';
    if (CITABLE[rec.kind]) return 'PDF';
    return 'Open';
  }

  function addChip(container, facet, value) {
    var chip = el('span', 'chip chip-' + facet, labelFor(facet, value));
    chip.title = 'Filter by ' + labelFor(facet, value);
    chip.onclick = function () { state.sel[facet][value] = true; applyFilters(); };
    container.appendChild(chip);
  }

  function renderSummaryInto(container, text) {
    var paras = String(text).split(/\n\n+/);
    container.innerHTML = '';
    for (var i = 0; i < paras.length; i++) {
      var p = document.createElement('p');
      p.innerHTML = paras[i];
      container.appendChild(p);
    }
    var links = container.getElementsByTagName('a');
    for (var j = 0; j < links.length; j++) { links[j].target = '_blank'; links[j].rel = 'noopener'; }
  }

  function renderItem(rec) {
    var li = el('li', 'pub-item' + (rec.tier === 'tail' ? ' tail-item' : ''));

    // Title
    var t = el('div', 'pub-title');
    if (rec.url) {
      var a = el('a', null, rec.title || 'Untitled');
      a.href = rec.url; a.target = '_blank'; a.rel = 'noopener';
      t.appendChild(a);
    } else {
      t.appendChild(document.createTextNode(rec.title || 'Untitled'));
    }
    li.appendChild(t);

    // Meta line: kind badge · venue · year · confidence
    var meta = el('div', 'pub-meta');
    meta.appendChild(el('span', 'badge badge-kind', KIND_LABELS[rec.kind] || prettify(rec.kind)));
    if (rec.tier === 'tail') meta.appendChild(el('span', 'badge badge-tail', 'tail'));
    var bits = [];
    if (rec.venue) bits.push(rec.venue);
    if (rec.year) bits.push(String(rec.year));
    if (rec.stars != null) bits.push('\u2605 ' + rec.stars);
    if (rec.cited != null) bits.push('cited by ' + rec.cited);
    if (bits.length) meta.appendChild(el('span', 'pub-dim', ' ' + bits.join(' · ')));
    if (rec.confidence) {
      var conf = el('span', 'conf');
      conf.appendChild(el('span', 'conf-dot conf-' + rec.confidence));
      conf.appendChild(el('span', 'conf-label', rec.confidence));
      meta.appendChild(conf);
    }
    li.appendChild(meta);

    // Authors
    if (rec.authors && rec.authors.length) {
      li.appendChild(el('div', 'pub-authors', rec.authors.join(', ')));
    }

    // Integration / evidence (repos and vendored uses)
    if (rec.integration || rec.evidence) {
      var ev = el('div', 'pub-evidence');
      if (rec.integration) ev.appendChild(el('span', 'badge badge-integration', INTEGRATION_LABELS[rec.integration] || prettify(rec.integration)));
      if (rec.evidence) ev.appendChild(el('span', 'evidence-text', 'evidence: ' + rec.evidence));
      li.appendChild(ev);
    }

    // Needs flag
    if (rec.needs) {
      li.appendChild(el('div', 'pub-needs', '\u2691 needs: ' + rec.needs));
    }

    // Chips
    var chips = el('div', 'pub-chips');
    (rec.sdv_component || []).forEach(function (v) { addChip(chips, 'sdv_component', v); });
    (rec.use_case || []).forEach(function (v) { addChip(chips, 'use_case', v); });
    (rec.industry || []).forEach(function (v) { addChip(chips, 'industry', v); });
    if (chips.childNodes.length) li.appendChild(chips);

    // Actions
    var actions = el('div', 'pub-actions');
    if (rec.url) {
      var link = el('a', 'pub-action', actionLabel(rec));
      link.href = rec.url; link.target = '_blank'; link.rel = 'noopener';
      actions.appendChild(link);
    }
    if (rec.doi) {
      var doi = el('a', 'pub-action', 'DOI');
      doi.href = /^https?:/.test(rec.doi) ? rec.doi : 'https://doi.org/' + rec.doi;
      doi.target = '_blank'; doi.rel = 'noopener';
      actions.appendChild(doi);
    }
    if (CITABLE[rec.kind]) actions.appendChild(makeBibLink(rec));
    if (rec.url) {
      var copy = el('a', 'pub-action', 'Copy link');
      copy.href = '#';
      copy.onclick = function (e) {
        e.preventDefault();
        if (navigator.clipboard) navigator.clipboard.writeText(rec.url);
        copy.textContent = 'Copied';
        setTimeout(function () { copy.textContent = 'Copy link'; }, 1200);
      };
      actions.appendChild(copy);
    }

    // Summary
    if (rec.summary) {
      var sum = el('div', 'pub-summary' + (state.summaryExpanded ? ' open' : ''));
      renderSummaryInto(sum, rec.summary);
      var toggle = el('a', 'pub-action pub-summary-toggle');
      toggle.href = '#';
      var setArrow = function (open) { toggle.textContent = open ? 'Summary \u25be' : 'Summary \u25b8'; };
      setArrow(state.summaryExpanded);
      toggle.onclick = function (e) {
        e.preventDefault();
        var open = sum.className.indexOf('open') === -1;
        sum.className = 'pub-summary' + (open ? ' open' : '');
        setArrow(open);
      };
      actions.appendChild(toggle);
      li.appendChild(actions);
      li.appendChild(sum);
    } else {
      li.appendChild(actions);
    }

    return li;
  }

  /* ---------- Grouping & sorting ---------- */
  function groupHeadersFor(rec) {
    var g = state.group;
    if (g === 'none') return [''];
    if (g === 'kind') return [KIND_LABELS[rec.kind] || prettify(rec.kind)];
    if (g === 'year') return [rec.year ? String(rec.year) : 'Undated'];
    if (g === 'confidence') return [rec.confidence ? prettify(rec.confidence) : 'Unrated'];
    var vals = valuesOf(rec, g);
    if (!vals.length) return ['Other'];
    return vals.map(function (v) { return labelFor(g, v); });
  }

  /* Importance = blend of confidence and a bounded impact. Repo weight (stars +
     reuse/collaboration/effort) is capped below top papers; docs/blogs get a
     neutral impact. Paper impact = citations (OpenAlex, which undercounts CTGAN). */
  var IMP_CONF = { high: 1, medium: 0.66, low: 0.33 };
  function importance(rec) {
    var conf = IMP_CONF[rec.confidence] != null ? IMP_CONF[rec.confidence] : 0.15;
    var impact;
    if (rec.kind === 'code_repo' || rec.stars != null) {
      var w = (rec.stars || 0) + 2 * (rec.forks || 0) + 5 * (rec.contributors || 0) + 0.1 * (rec.commits || 0);
      impact = 0.6 * Math.min(1, Math.log1p(w) / Math.log1p(8000));  // ceiling 0.6 < a top paper's 1.0
    } else if (rec.cited != null) {
      impact = Math.min(1, Math.log1p(rec.cited) / Math.log1p(1500));
    } else {
      impact = 0.3;
    }
    return 0.5 * conf + 0.5 * impact;
  }
  function sortWithin(arr) {
    var key = state.sortWithin;
    arr.sort(function (a, b) {
      if (key === 'title') return (a.title || '').toLowerCase().localeCompare((b.title || '').toLowerCase());
      if (key === 'importance') {
        var di = importance(b) - importance(a);
        if (di) return di;
      }
      var dy = (b.year || 0) - (a.year || 0);
      if (dy) return dy;
      return (a.title || '').toLowerCase().localeCompare((b.title || '').toLowerCase());
    });
    return arr;
  }

  function headerOrder(headers) {
    var g = state.group;
    if (g === 'kind') {
      var rank = {};
      KIND_ORDER.forEach(function (k, i) { rank[KIND_LABELS[k]] = i; });
      return headers.sort(function (A, B) {
        var ra = rank[A] == null ? 99 : rank[A], rb = rank[B] == null ? 99 : rank[B];
        return ra !== rb ? ra - rb : A.localeCompare(B);
      });
    }
    if (g === 'year') {
      return headers.sort(function (A, B) {
        if (A === 'Undated') return 1; if (B === 'Undated') return -1;
        return (parseInt(B, 10) || 0) - (parseInt(A, 10) || 0);
      });
    }
    if (g === 'confidence') {
      var cr = { High: 3, Medium: 2, Low: 1, Unrated: 0 };
      return headers.sort(function (A, B) { return (cr[B] || 0) - (cr[A] || 0); });
    }
    return headers; // component/use_case/industry: keep insertion order (by size)
  }

  function renderResults() {
    var items = filteredData();
    var mount = els.results;
    mount.innerHTML = '';

    if (!items.length) {
      mount.appendChild(el('div', 'empty', 'No entries match the current filters.'));
      return;
    }

    if (state.group === 'none') {
      var ul = el('ul', 'pub-list');
      sortWithin(items).forEach(function (r) { ul.appendChild(renderItem(r)); });
      mount.appendChild(ul);
      return;
    }

    var groups = {}, order = [], sizes = {};
    items.forEach(function (rec) {
      groupHeadersFor(rec).forEach(function (h) {
        if (!groups[h]) { groups[h] = []; order.push(h); }
        groups[h].push(rec);
      });
    });
    order.forEach(function (h) { sizes[h] = groups[h].length; });
    // size-ordered facets: sort headers by group size desc before headerOrder no-op
    if (['sdv_component', 'use_case', 'industry'].indexOf(state.group) >= 0) {
      order.sort(function (A, B) { return sizes[B] - sizes[A] || A.localeCompare(B); });
    }
    var headers = headerOrder(order);

    var frag = document.createDocumentFragment();
    headers.forEach(function (h) {
      var sec = el('div', 'pub-group');
      var head = el('h3');
      head.appendChild(document.createTextNode(h));
      head.appendChild(el('span', 'group-count', ' (' + groups[h].length + ')'));
      sec.appendChild(head);
      var ul = el('ul', 'pub-list');
      sortWithin(groups[h].slice()).forEach(function (r) { ul.appendChild(renderItem(r)); });
      sec.appendChild(ul);
      frag.appendChild(sec);
    });
    mount.appendChild(frag);
  }

  /* ---------- Tails (merged into the main list) ---------- */
  function fromHits(hits) {
    var set = {};
    (hits || []).forEach(function (h) { var c = HITS2COMPONENT[h]; if (c) set[c] = 1; });
    return Object.keys(set);
  }
  function normalizeCite(r) {
    var loc = r.primary_location || {};
    var authors = (r.authorships || []).map(function (a) { return (a.author || {}).display_name; }).filter(Boolean);
    return {
      id: r.id, title: r.title || 'Untitled', year: r.publication_year || null,
      kind: TYPE2KIND[r.type] || 'paper', url: loc.landing_page_url || r.doi || r.id, doi: r.doi || '',
      authors: authors, sdv_component: [], use_case: [], industry: [],
      cited: r.cited_by_count || 0, confidence: null, tier: 'tail'
    };
  }
  function normalizeGh(r) {
    var yr = parseInt((r.created || '').slice(0, 4), 10) || null;
    var authors = [r.owner].concat(r.top_contributors || []).filter(Boolean);
    return {
      id: 'gh-' + r.repo, title: r.repo, url: 'https://github.com/' + r.repo,
      kind: 'code_repo', sdv_component: fromHits((r.hit_patterns || '').split('|')),
      use_case: [], industry: [], authors: authors, summary: r.description || '',
      year: yr, stars: r.stars || 0, forks: r.forks || 0,
      contributors: r.contributors || 0, commits: r.commits || 0,
      confidence: null, tier: 'tail'
    };
  }
  function loadCite(done) {
    if (CITE) { done(); return; }
    fetch(TAIL_PATH).then(function (r) { if (!r.ok) throw new Error('HTTP ' + r.status); return r.json(); })
      .then(function (raw) { CITE = (raw || []).map(normalizeCite);
        els.tailLabel.textContent = 'Citation tail (' + CITE.length + ')'; done(); })
      .catch(function (e) { els.errors.textContent = 'Could not load citation tail: ' + e.message;
        els.toggleTail.checked = false; state.showTail = false; });
  }
  function loadGh(done) {
    if (GH) { done(); return; }
    fetch(GITHUB_PATH).then(function (r) { if (!r.ok) throw new Error('HTTP ' + r.status); return r.json(); })
      .then(function (raw) { GH = ((raw && raw.repos) || raw || []).map(normalizeGh);
        els.githubLabel.textContent = 'GitHub repo tail (' + GH.length + ')'; done(); })
      .catch(function (e) { els.errors.textContent = 'Could not load GitHub tail: ' + e.message;
        els.toggleGithub.checked = false; state.showGithub = false; });
  }

  /* ---------- BibTeX ---------- */
  var BIB_TYPE = { paper: 'article', preprint: 'misc', thesis: 'mastersthesis' };
  function bibKey(rec) {
    return rec.id || (rec.title || 'untitled').toLowerCase().replace(/[^a-z0-9]+/g, '').slice(0, 24) + (rec.year || '');
  }
  function buildBibtex(rec) {
    var out = ['@' + (BIB_TYPE[rec.kind] || 'misc') + '{' + bibKey(rec) + ','];
    function push(k, v) { if (v) out.push('  ' + k + ' = {' + String(v).replace(/[\n\r]+/g, ' ') + '},'); }
    push('author', (rec.authors || []).join(' and '));
    push('title', '{' + (rec.title || '') + '}');
    push('year', rec.year);
    push('note', rec.venue);
    push('doi', rec.doi);
    push('url', rec.url);
    if (out.length > 1) out[out.length - 1] = out[out.length - 1].replace(/,\s*$/, '');
    out.push('}');
    return out.join('\n');
  }
  function makeBibLink(rec) {
    var a = el('a', 'pub-action', 'BibTeX');
    var blob = new Blob([buildBibtex(rec)], { type: 'text/plain' });
    a.href = URL.createObjectURL(blob);
    a.download = bibKey(rec) + '.bib';
    return a;
  }

  /* ---------- Apply ---------- */
  function updateCount() {
    var total = activeData().length, n = filteredData().length;
    els.count.textContent = n === total ? '(' + n + ')' : '(' + n + ' of ' + total + ')';
  }
  function applyFilters() {
    computeUniverse();
    rebuildFacets();
    renderResults();
    updateCount();
  }

  /* ---------- Events ---------- */
  function wire() {
    els.title.addEventListener('input', function () { state.titleQuery = this.value; applyFilters(); });
    els.authorSearch.addEventListener('input', function () { state.authorQuery = this.value; buildCheckboxFacet('authors'); });

    els.sortGroup.addEventListener('change', function () { state.group = this.value; renderResults(); });
    els.sortWithin.addEventListener('change', function () { state.sortWithin = this.value; renderResults(); });

    els.btnSummaries.addEventListener('click', function () {
      state.summaryExpanded = !state.summaryExpanded;
      this.setAttribute('aria-pressed', String(state.summaryExpanded));
      this.textContent = state.summaryExpanded ? 'Hide summaries' : 'Show summaries';
      renderResults();
    });

    els.btnClear.addEventListener('click', function () {
      FACET_KEYS.forEach(function (fk) { state.sel[fk] = {}; });
      state.titleQuery = ''; state.authorQuery = '';
      els.title.value = ''; els.authorSearch.value = '';
      applyFilters();
    });

    els.toggleTail.addEventListener('change', function () {
      state.showTail = this.checked;
      if (state.showTail) loadCite(applyFilters); else applyFilters();
    });
    els.toggleGithub.addEventListener('change', function () {
      state.showGithub = this.checked;
      els.minStarsWrap.style.display = this.checked ? '' : 'none';
      if (state.showGithub) loadGh(applyFilters); else applyFilters();
    });
    els.minStars.addEventListener('input', function () {
      state.minStars = parseInt(this.value, 10) || 0;
      if (state.showGithub) applyFilters();
    });
  }

  /* ---------- Init ---------- */
  function computeUniverse() {
    FACET_KEYS.forEach(function (fk) {
      var set = {};
      activeData().forEach(function (rec) { valuesOf(rec, fk).forEach(function (v) { set[v] = 1; }); });
      UNIVERSE[fk] = Object.keys(set);
    });
  }

  function init() {
    els = {
      errors: $('pubs-errors'), results: $('pubs-results'), count: $('pubs-count'),
      title: $('facet-title'), authorSearch: $('author-search'),
      kind: $('facet-kind'), sdv_component: $('facet-component'), use_case: $('facet-usecase'),
      industry: $('facet-industry'), confidence: $('facet-confidence'), authors: $('facet-authors'),
      year: $('facet-years'),
      sortGroup: $('sort-group'), sortWithin: $('sort-within'),
      btnSummaries: $('btn-toggle-summaries'), btnClear: $('btn-clear'),
      toggleTail: $('toggle-tail'), tailLabel: $('tail-label'),
      toggleGithub: $('toggle-github'), githubLabel: $('github-label'),
      minStars: $('min-stars'), minStarsWrap: $('minstars-wrap')
    };
    wire();

    fetch(INDEX_PATH).then(function (r) {
      if (!r.ok) throw new Error('HTTP ' + r.status);
      return r.json();
    }).then(function (data) {
      DATA = data || [];
      computeUniverse();
      applyFilters();
    }).catch(function (e) {
      els.errors.textContent = 'Could not load ' + INDEX_PATH + ': ' + e.message +
        '. Serve over HTTP (python3 -m http.server), not the file:// scheme.';
    });
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
